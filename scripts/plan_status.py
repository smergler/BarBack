"""Generate plans/STATUS.md from the checkboxes in plans/*/PLAN.md.

    .venv/bin/python scripts/plan_status.py [--exclude SLUG ...]

Status is derived, never hand-edited. Dependencies are not evaluated: "next" is the
first open subtask that is not marked `Requires human`.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

PLANS_DIR = Path(__file__).resolve().parent.parent / "plans"
SUBTASK = re.compile(r"^- \[([ x~!>])\] \**([A-Z]?\d+\.\d+)")
HEADER = "<!-- GENERATED by scripts/plan_status.py - do not edit -->"


def parse_plan(path: Path) -> dict:
    blocks: list[tuple[str, str, list[str]]] = []
    for line in path.read_text().splitlines():
        m = SUBTASK.match(line)
        if m:
            blocks.append((m.group(1), m.group(2), [line]))
        elif line.startswith("#"):
            blocks.append(("", "", []))  # a heading ends the current block
        elif blocks and blocks[-1][0]:
            blocks[-1][2].append(line)

    result = {"slug": path.parent.name, "done": 0, "open_agent": 0, "open_human": 0,
              "blocked": 0, "transferred": 0, "total": 0, "next_agent": "-"}
    for mark, sid, lines in blocks:
        if not mark:
            continue
        result["total"] += 1
        if mark == "x":
            result["done"] += 1
        elif mark == "!":
            result["blocked"] += 1
        elif mark == ">":
            result["transferred"] += 1
        elif any("Requires human" in ln for ln in lines):
            result["open_human"] += 1
        else:
            result["open_agent"] += 1
            if result["next_agent"] == "-":
                result["next_agent"] = sid
    return result


def render(plans: list[dict]) -> str:
    rows = [
        HEADER,
        "",
        "# Plan status",
        "",
        "Dependencies are not evaluated: *Next* is the first open subtask not marked `Requires human`.",
        "",
        "| Plan | Done | Open (agent) | Open (human) | Blocked | Transferred | Next |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in plans:
        rows.append(
            f"| {p['slug']} | {p['done']}/{p['total']} | {p['open_agent']} | {p['open_human']} "
            f"| {p['blocked']} | {p['transferred']} | {p['next_agent']} |"
        )
    return "\n".join(rows) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Write plans/STATUS.md from plan checkboxes.")
    parser.add_argument("--exclude", action="append", default=[], metavar="SLUG")
    args = parser.parse_args()
    paths = sorted(p for p in PLANS_DIR.glob("*/PLAN.md") if p.parent.name not in args.exclude)
    (PLANS_DIR / "STATUS.md").write_text(render([parse_plan(p) for p in paths]))


if __name__ == "__main__":
    main()
